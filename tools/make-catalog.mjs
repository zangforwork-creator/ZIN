// Builds site/catalog.js from book-inventory.json. Run: node tools/make-catalog.mjs
// Keeps only public-safe facts: titles, authors, edition, pages, check status. No file paths, hashes or names from inside documents.
import { readFileSync, writeFileSync } from 'node:fs';
const inv = JSON.parse(readFileSync(new URL('../book-inventory.json', import.meta.url), 'utf8'));
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const check = v => !v ? 'Not recorded' : /^verified_title/.test(v) ? 'Title page checked' : v === 'verified_metadata' ? 'File metadata only' : 'Checked';
const REF = /outside the 10/i;

const courses = new Map(), reference = [];
for (const b of inv.books) {
  const item = { kind: 'book', title: b.title, authors: b.authors || [], edition: b.edition || null, pages: b.pages || null, check: check(b.verification) };
  if (REF.test(b.course)) { reference.push(item); continue; }
  if (!courses.has(b.course)) courses.set(b.course, []);
  courses.get(b.course).push(item);
}
for (const d of inv.documents || []) {
  if (!courses.has(d.course)) courses.set(d.course, []);
  courses.get(d.course).push({ kind: 'slides', title: d.title, authors: [], edition: null, pages: null, format: d.format,
    check: d.status === 'structure_and_text_readable' ? 'Text readable' : 'Checked' });
}
const out = { checked: inv.checked_date, courses: [...courses].map(([name, items]) => ({ slug: slug(name), name, items })), reference };
writeFileSync(new URL('../site/catalog.js', import.meta.url),
  '// Generated by tools/make-catalog.mjs from book-inventory.json. Do not edit by hand.\nwindow.CATALOG = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(out.courses.length + ' courses, ' + out.courses.reduce((n, c) => n + c.items.length, 0) + ' items, ' + reference.length + ' reference');
